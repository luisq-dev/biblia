  static final Map<String, BibleBook> _byId = <String, BibleBook>{
    for (final BibleBook book in books) book.id: book,
  };

  static final Map<String, int> _indexById = <String, int>{
    for (int i = 0; i < books.length; i++) books[i].id: i,
  };

  static const int totalChapters = 1189;

  static BibleBook? byId(String id) => _byId[id.toUpperCase()];

  static int indexOf(String id) => _indexById[id.toUpperCase()] ?? -1;

  static String displayName(String bookId) => byId(bookId)?.name ?? bookId;

  static String displayAbbreviation(String bookId) =>
      byId(bookId)?.abbreviation ?? bookId;

  static List<BibleBook> byTestament(Testament testament) =>
      books.where((BibleBook book) => book.testament == testament).toList();
